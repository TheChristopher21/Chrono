const TRANSLATABLE_PROPS = ['aria-label', 'placeholder', 'title'];

const translateText = (text, language) => {
    if (language !== 'en' || !text.trim()) return text;
    return ENGLISH_REPLACEMENTS.reduce(
        (translated, [german, english]) => translated.split(german).join(english),
        text,
    );
};

const translateNode = (node, language) => {
    if (typeof node === 'string') return translateText(node, language);
    if (!isValidElement(node)) return node;

    const translatedProps = {};
    TRANSLATABLE_PROPS.forEach((propName) => {
        if (typeof node.props[propName] === 'string') {
            translatedProps[propName] = translateText(node.props[propName], language);
        }
    });
    if (node.props.children !== undefined) {
        translatedProps.children = Children.map(
            node.props.children,
            (child) => translateNode(child, language),
        );
    }
    return cloneElement(node, translatedProps);
};

export const PmsTranslationBoundary = ({ children }) => {
    const { language } = useTranslation();
    return Children.map(children, (child) => translateNode(child, language));
};

export const PmsLanguageSwitch = () => {
    const { language, setLanguage } = useContext(LanguageContext);
    return (
        <PmsTranslationBoundary>
        <div className="pms-language-switch" role="group" aria-label="Sprache wählen">
            <button type="button" className={language === 'de' ? 'is-active' : ''} onClick={() => setLanguage('de')}>DE</button>
            <button type="button" className={language === 'en' ? 'is-active' : ''} onClick={() => setLanguage('en')}>EN</button>
        </div>
        </PmsTranslationBoundary>
    );
};

export const usePmsLocale = () => {
    const { language } = useTranslation();
    return language === 'en' ? 'en-GB' : 'de-CH';
};
