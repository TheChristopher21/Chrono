async page => {
  const checks=[],errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  const check=(ok,message)=>{if(!ok)throw new Error(message);checks.push(message);};
  const root=()=>page.locator('[data-workspace-pane]:not([aria-hidden]) .admin-workspace');
  const center=()=>root().locator('.aw-requests');
  const order=()=>center().locator('.awr-list .awr-row-copy strong').allTextContents();
  await page.setViewportSize({width:1366,height:768});
  await page.goto('http://127.0.0.1:5173/admin/dashboard-neu?tab=requests');
  await center().locator('.awr-list .awr-row').first().waitFor();
  check((await order()).join(',')==='Nina Keller,Mirjam Burkart,Luca Meier,Lea Sommer','Unified inbox sorts corrections and vacations chronologically');
  check(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1),'Request workspace fits laptop viewport');
  check(await center().getByRole('button',{name:'Genehmigen',exact:true}).evaluate(e=>e.getBoundingClientRect().bottom<=innerHeight),'Approval visible without scrolling');
  await center().getByRole('combobox',{name:'Reihenfolge',exact:true}).selectOption('desc');
  check((await order()).join(',')==='Lea Sommer,Luca Meier,Mirjam Burkart,Nina Keller','Descending order reverses actual dates');
  await center().getByRole('combobox',{name:'Reihenfolge',exact:true}).selectOption('asc');
  await center().getByRole('button',{name:/Weitere Filter/}).click();
  await center().getByLabel('Datum eingrenzen',{exact:true}).fill('2026-09-24');
  check((await order()).join(',')==='Luca Meier','Date filter includes dates inside vacation ranges');
  await center().getByLabel('Datum eingrenzen',{exact:true}).fill('');
  await center().getByRole('button',{name:/Weitere Filter/}).click();
  await center().getByRole('combobox',{name:'Person',exact:true}).selectOption('Mirjam');
  await page.waitForURL(/requestUser=Mirjam/);
  await page.waitForFunction(()=>{const rows=document.querySelectorAll('[data-workspace-pane]:not([aria-hidden]) .awr-list .awr-row-copy strong');return rows.length===1&&rows[0].textContent==='Mirjam Burkart';});
  check((await order()).join(',')==='Mirjam Burkart','Person filter is exact and reflected in URL');
  await center().getByRole('button',{name:/Personenfilter entfernen/}).click();
  await center().locator('[data-request-key="vacation:12"] button').click();
  await center().getByRole('textbox',{name:'Kommentar zur Entscheidung',exact:true}).fill('Im Team abgestimmt');
  await center().getByRole('button',{name:'Genehmigen',exact:true}).click();
  await center().locator('.awr-feedback').filter({hasText:'Antrag genehmigt'}).waitFor();
  check(!(await order()).includes('Luca Meier'),'Approved request leaves pending list without a page reload');
  await center().getByRole('combobox',{name:'Status',exact:true}).selectOption('approved');
  await center().locator('[data-request-key="vacation:12"] button').click();
  check((await center().locator('.awr-detail-scroll').innerText()).includes('Im Team abgestimmt'),'History shows saved decision note');
  await center().getByRole('button',{name:'Urlaub löschen',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Urlaub löschen bestätigen'});await dialog.waitFor();
  check((await dialog.innerText()).includes('Luca Meier'),'Deletion confirmation identifies selected person');
  await dialog.getByRole('button',{name:'Abbrechen',exact:true}).click();
  await center().getByRole('combobox',{name:'Status',exact:true}).selectOption('pending');
  await page.screenshot({path:'output/playwright/chrono-workspace-v2-requests-final-light.png',fullPage:true,animations:'disabled'});
  await page.locator('nav[aria-label="Hauptnavigation"]:visible').getByRole('button',{name:'Dark Mode',exact:true}).click();
  await page.screenshot({path:'output/playwright/chrono-workspace-v2-requests-final-dark.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Request controls and details fit mobile width');
  await page.screenshot({path:'output/playwright/chrono-workspace-v2-requests-final-mobile.png',fullPage:true,animations:'disabled'});
  return {checks,errors};
}
